"""Post-run retrospective (SRP: proposal only, no edits)."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brand_tokens as bt  # noqa: E402


def main() -> int:
    """Parse arguments and emit retro suggestions."""
    parser = argparse.ArgumentParser(description="Post-run retrospective")
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--version", action="version", version=f"rebrander {bt.get_version()}")
    args = parser.parse_args()

    out = args.out or (args.root / "RETRO.md")
    # gather recent git log if available
    git_log = ""
    try:
        r = subprocess.run(["git", "-C", str(args.root), "log", "--oneline", "-10"], capture_output=True, text=True)
        git_log = r.stdout.strip()
    except Exception:
        git_log = "(git unavailable)"

    lines = [
        "# Retro",
        "",
        "## Recent commits",
        "```",
        git_log or "(none)",
        "```",
        "",
        "## Proposed environment improvements",
        "- Add navigation pointers for frequently accessed files.",
        "- Add automated checks for recurring failures.",
        "- Update coding standards if violations repeated.",
        "- Improve tooling if manual steps repeated.",
        "",
        "Generated by retro.py.",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Retro written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
