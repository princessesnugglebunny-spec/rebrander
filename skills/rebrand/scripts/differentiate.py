"""Differentiation pass: propose a unique product identity (SRP: proposal only)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brand_tokens as bt  # noqa: E402


def main() -> int:
    """Parse arguments and emit DESIGN.md."""
    parser = argparse.ArgumentParser(description="Propose a differentiated product design")
    parser.add_argument("--brand", required=True, type=Path)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--version", action="version", version=f"rebrander {bt.get_version()}")
    args = parser.parse_args()

    brand = bt.load_brand(args.brand)
    target = brand.get("target", {})
    name = target.get("name", "NewProduct")
    out = args.out or (args.root / "DESIGN.md")

    lines = [
        f"# Differentiated design — {name}",
        "",
        "Principle learned: (fill in from the rebrand study)",
        "",
        "## Proposed identity",
        f"- Name: {name}",
        f"- Slug: {target.get('slug', '')}",
        f"- Tagline: {target.get('tagline', '(define a new value proposition)')}",
        f"- Colors: {target.get('colors', {})}",
        "",
        "## Differentiation checklist",
        "- Change the setting / use case (not the original's).",
        "- Change the art direction and theme.",
        "- Change the core fantasy or user story.",
        "- Keep only the underlying principle; drop source-specific UX.",
        "- Run judge-look (references/judge-look.md) over generated UI.",
        "",
        "## Notes",
        "Generated by differentiate.py. Review and refine before shipping.",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Design written to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
